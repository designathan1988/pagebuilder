const NOTICE = 'Generated by `npm run gen` (tools/gen/generate.ts) from the packages named in "from". Do not edit: change the generator or the package version and run npm run gen.';

interface WebrefFeature {
  name: string;
  href?: string;
  syntax?: string;
  for?: string[];
  initial?: string;
  inherited?: string;
  longhands?: string[];
  legacyAliasOf?: string;
}
interface WebrefCss {
  properties: WebrefFeature[];
  types: WebrefFeature[];
  functions: WebrefFeature[];
}

const version = packageVersion;

// ---------------------------------------------------------------- CSS

// Keywords reachable in a syntax without entering a function: those are the candidates for a
// property's keyword list. Candidates the lexer does not accept on their own are dropped.
function keywordCandidates(lexer: Lexer, root: DSNode | null): string[] {
  const found: string[] = [];
  const seen = new Set<string>();
  const visit = (node: DSNode | null): void => {
    if (node === null) return;
    switch (node.type) {
      case 'Keyword':
        if (!found.includes(node.name)) found.push(node.name);
        return;
      case 'Group':
        node.terms.forEach(visit);
        return;
      case 'Multiplier':
      case 'Boolean':
        visit(node.term);
        return;
      case 'Type': {
        if (node.name.endsWith('()') || seen.has(`type:${node.name}`)) return;
        seen.add(`type:${node.name}`);
        visit(lexer.getType(node.name)?.syntax ?? null);
        return;
      }
      case 'Property': {
        if (seen.has(`property:${node.name}`)) return;
        seen.add(`property:${node.name}`);
        visit(lexer.getProperty(node.name)?.syntax ?? null);
        return;
      }
      default:
        return;
    }
  };
  visit(root);
  return found;
}

function expandLonghands(byName: Map<string, WebrefFeature>, name: string): string[] {
  const own = byName.get(name)?.longhands ?? [];
  return own.flatMap((longhand) => {
    const sub = byName.get(longhand)?.longhands ?? [];
    return sub.length > 0 ? expandLonghands(byName, longhand) : [longhand];
  });
}

function inherited(text: string | undefined): boolean | null {
  if (text === 'yes') return true;
  if (text === 'no') return false;
  return null;
}

export interface GeneratedCssData {
  properties: Record<string, { syntax: string | null }>;
  types: Record<string, string>;
  units: Record<string, string[]>;
  scopedFunctions: Record<string, string[]>;
}

// The scope a webref "for" names, as the syntax holder it roots: a type ("<basic-shape>" → basic-shape),
// a function ("<image-set()>", "attr()" → image-set(), attr()) or a property ("clip"); null for an at-rule.
function scopeRoot(scope: string): string | null {
  if (scope.startsWith('@')) return null;
  return scope.replace(/^<(.*)>$/, '$1');
}

// Several functions share a name only through their scopes (rect() of <basic-shape> and of clip; type()
// of image-set(), attr() and @function). CSSTree has no scopes and matches a <name()> reference only by
// the function's own name, so each scoped definition is written inline into the syntaxes its scope
// reaches: <basic-shape-rect> gets css-shapes' rect(), clip gets the legacy rect(). A syntax both scopes
// reach keeps the reference unresolved.
export function inlineScopedFunctions(
  properties: Record<string, string | null>,
  types: Record<string, string>,
  definitions: readonly { name: string; syntax?: string; for?: string[] }[],
): { properties: Record<string, string | null>; types: Record<string, string>; scopes: Record<string, string[]> } {
  const outProperties = { ...properties };
  const outTypes = { ...types };
  const scopes: Record<string, string[]> = {};
  const holderSyntax = (holder: string) => (holder.startsWith('property:') ? (outProperties[holder.slice(9)] ?? null) : (outTypes[holder.slice(5)] ?? null));
  const references = (syntax: string): string[] => [
    ...[...syntax.matchAll(/<([a-z][a-z0-9-]*(?:\(\))?)(?:\s[^>]*)?>/g)].map((m) => `type:${m[1] ?? ''}`),
    ...[...syntax.matchAll(/<'([a-z-]+)'>/g)].map((m) => `property:${m[1] ?? ''}`),
  ];
  const reachable = (root: string): Set<string> => {
    const seen = new Set<string>();
    const queue = [root];
    while (queue.length > 0) {
      const holder = queue.shift() as string;
      if (seen.has(holder)) continue;
      seen.add(holder);
      const syntax = holderSyntax(holder);
      if (syntax !== null) queue.push(...references(syntax));
    }
    return seen;
  };
  const names = [...new Set(definitions.map((d) => d.name))].filter((name) => {
    const same = definitions.filter((d) => d.name === name && d.syntax !== undefined);
    return name.endsWith('()') && same.length > 1 && same.every((d) => d.for !== undefined);
  });
  for (const name of names.sort()) {
    const chosen = new Map<string, string>(); // holder → inline syntax
    const ambiguous = new Set<string>();
    for (const definition of definitions.filter((d) => d.name === name && d.syntax !== undefined)) {
      for (const scope of definition.for ?? []) {
        const root = scopeRoot(scope);
        if (root === null) continue;
        scopes[name.slice(0, -2)] = [...(scopes[name.slice(0, -2)] ?? []), root];
        const start = root in outProperties && !(root in outTypes) ? `property:${root}` : `type:${root}`;
        for (const holder of reachable(start)) {
          const syntax = holderSyntax(holder);
          if (syntax === null || !syntax.includes(`<${name}>`)) continue;
          if (chosen.has(holder) && chosen.get(holder) !== definition.syntax) ambiguous.add(holder);
          else chosen.set(holder, definition.syntax as string);
        }
      }
    }
    for (const [holder, inline] of chosen) {
      if (ambiguous.has(holder)) continue;
      const syntax = holderSyntax(holder) as string;
      const rewritten = syntax.split(`<${name}>`).join(`[ ${inline} ]`);
      if (holder.startsWith('property:')) outProperties[holder.slice(9)] = rewritten;
      else outTypes[holder.slice(5)] = rewritten;
    }
  }
  return { properties: outProperties, types: outTypes, scopes };
}

export function generateCss(): GeneratedCssData & Record<string, unknown> {
  const webref = require('@webref/css/css.json') as WebrefCss;
  const byName = new Map(webref.properties.map((p) => [p.name, p]));
  // A type or function scoped to one feature ("for") is kept under its plain name when no other
  // definition shares that name; functions that exist only in scoped versions are written inline into
  // the syntaxes their scope reaches (inlineScopedFunctions).
  const definitions = [...webref.types, ...webref.functions].filter((t) => t.syntax !== undefined);
  const sharing = (name: string) => definitions.filter((t) => t.name === name).length;
  const inlined = inlineScopedFunctions(
    Object.fromEntries(webref.properties.map((p) => [p.name, p.syntax ?? null])),
    Object.fromEntries(definitions.filter((t) => t.for === undefined || sharing(t.name) === 1).map((t) => [t.name, t.syntax as string])),
    definitions,
  );
  const syntaxes = { properties: inlined.properties, types: inlined.types };
  const matcher: CssMatcher = createCssMatcher(syntaxes);
  const lexer = matcher.lexer as Lexer & { units: Record<string, string[]>; cssWideKeywords: string[] };
  const units: Record<string, string[]> = { ...lexer.units, percentage: ['%'] };
  const allUnits = Object.values(units).flat();
  const cssWide = new Set(lexer.cssWideKeywords);

  const properties: Record<string, { syntax: string | null } & Record<string, unknown>> = {};
  for (const p of [...webref.properties].sort((a, b) => a.name.localeCompare(b.name))) {
    const syntax = syntaxes.properties[p.name] ?? null;
    const accepts = (value: string) => syntax !== null && matcher.match(p.name, value) === null;
    const keywords = syntax === null ? [] : keywordCandidates(lexer, lexer.getProperty(p.name)?.syntax ?? null).filter((k) => !cssWide.has(k) && accepts(k));
    properties[p.name] = {
      syntax,
      initial: p.initial ?? null,
      inherited: inherited(p.inherited),
      longhands: expandLonghands(byName, p.name),
      legacyAliasOf: p.legacyAliasOf ?? null,
      keywords,
      units: allUnits.filter((u) => accepts(`1${u}`)),
    };
  }
  return {
    $generated: { notice: NOTICE, by: 'tools/gen/generate.ts', from: { '@webref/css': version('@webref/css'), 'css-tree': version('css-tree') } },
    units,
    properties,
    types: Object.fromEntries(Object.entries(syntaxes.types).sort(([a], [b]) => a.localeCompare(b))),
    // functions that exist only in scoped versions → the scope roots of those versions (written inline)
    scopedFunctions: inlined.scopes,
  };
}

// ---------------------------------------------------------------- browser support

// manifest/css-exclusions.json: keywords every browser parses but none implements. Each one is marked unsupported in
// every browser, with its evidence as the reason, so it leaves every generated list.
export const EXCLUSIONS_FILE = 'manifest/css-exclusions.json';

function applyExclusions(properties: Record<string, { keywords: Record<string, { chrome: unknown; firefox: unknown; safari: unknown; why: Record<string, string> }> }>): void {
  const { exclusions } = exclusionsFileSchema.parse(JSON.parse(fs.readFileSync(path.join(REPO_ROOT, EXCLUSIONS_FILE), 'utf8')));
  for (const x of exclusions) {
    // an excluded unit leaves the property's list in tools/gen/types.ts (generatedUnits); css-compat.json keeps units
    // per browser for every property alike
    if (x.keyword === null) continue;
    const entry = properties[x.property]?.keywords[x.keyword.toLowerCase()];
    if (entry === undefined) throw new Error(`${EXCLUSIONS_FILE}: ${x.property} has no keyword ${x.keyword} in the generated data`);
    const why = `excluded (${EXCLUSIONS_FILE}): ${x.evidence.note}`;
    entry.chrome = false;
    entry.firefox = false;
    entry.safari = false;
    entry.why = { chrome: why, firefox: why, safari: why };
  }
}

export function generateCompat(css: GeneratedCssData): unknown {
  const bcd = bcdVersion();
  const matcher = createCssMatcher({ properties: Object.fromEntries(Object.entries(css.properties).map(([name, p]) => [name, p.syntax])), types: css.types });
  const longhands = css.properties as Record<string, { longhands?: string[] }>;
  const { browsers, properties } = generateCompatProperties(Object.keys(css.properties), matcher.lexer, css.types, (name) => longhands[name]?.longhands ?? [], css.scopedFunctions);
  applyExclusions(properties as Record<string, { keywords: Record<string, { chrome: unknown; firefox: unknown; safari: unknown; why: Record<string, string> }> }>);
  // the general-purpose functions of CSS Values (calc(), min(), clamp()...), which no property's syntax names
  const webref = require('@webref/css/css.json') as WebrefCss;
  const valueFunctions = webref.functions.filter((f) => /\/css-values-\d+\//.test(f.href ?? '') && f.for === undefined).map((f) => f.name.replace(/\(\)$/, ''));
  return {
    $generated: { notice: NOTICE, by: 'tools/gen/generate.ts', from: { '@mdn/browser-compat-data': bcd, '@webref/css': version('@webref/css'), 'css-tree': version('css-tree') } },
    // the current stable release of each browser according to BCD
    browsers,
    valueFunctions: generateValueFunctions(valueFunctions),
    units: generateUnits(css.units),
    properties,
  };
}

// ---------------------------------------------------------------- HTML

type MetaValue = boolean | string | string[] | undefined | ((...args: unknown[]) => unknown);
interface MetaElement {
  [key: string]: unknown;
  attributes?: Record<string, { boolean?: boolean; deprecated?: boolean; enum?: unknown[]; list?: boolean }>;
}

// Some metadata depends on the element's attributes (an <a> is interactive only with href);
// html-validate encodes that as a function. The generated data says "conditional".
function flag(value: MetaValue): boolean | 'conditional' {
  if (typeof value === 'function') return 'conditional';
  return value === true || (Array.isArray(value) && value.length > 0) || (typeof value === 'string' && value.length > 0);
}

function list(value: unknown): unknown[] | null {
  return Array.isArray(value) ? (value as unknown[]) : null;
}

function descendants(value: unknown): { exclude: string[] }[] | null {
  if (!Array.isArray(value)) return null;
  return (value as { exclude?: string | string[] }[]).map((rule) => ({
    exclude: rule.exclude === undefined ? [] : Array.isArray(rule.exclude) ? rule.exclude : [rule.exclude],
  }));
}

export function generateHtml(): unknown {
  const module = require('html-validate/elements/html5') as { default?: Record<string, MetaElement> } & Record<string, MetaElement>;
  const meta = module.default ?? module;
  const elements: Record<string, unknown> = {};
  for (const tag of Object.keys(meta).filter((t) => t !== '*').sort()) {
    const m = meta[tag] as MetaElement;
    const attributes: Record<string, unknown> = {};
    for (const [name, a] of Object.entries(m.attributes ?? {}).sort(([x], [y]) => x.localeCompare(y))) {
      const values = (a.enum ?? []).filter((v): v is string => typeof v === 'string' && !/^\/.*\/$/.test(v));
      attributes[name] = {
        boolean: a.boolean === true,
        deprecated: a.deprecated === true,
        // the literal values html-validate lists; null when the attribute takes free text or a pattern
        enum: a.enum !== undefined && values.length === a.enum.length ? values : null,
      };
    }
    // html-validate lists the deprecated data-binding attributes of <select> (datasrc, datafld, dataformatas) among its
    // permitted content: no element bears those names, and the editor's refusal named them as elements a select takes
    const content = list(m.permittedContent)?.filter((entry) => typeof entry !== 'string' || entry.startsWith('@') || entry.replace(/[?*+]$/, '') in meta) ?? null;
    elements[tag] = {
      deprecated: m.deprecated !== undefined && m.deprecated !== false,
      void: m.void === true,
      foreign: m.foreign === true,
      // no element children allowed (html-validate lists an empty permitted content)
      textOnly: content !== null && content.length === 0 && m.void !== true,
      categories: {
        metadata: flag(m.metadata as MetaValue),
        flow: flag(m.flow as MetaValue),
        sectioning: flag(m.sectioning as MetaValue),
        heading: flag(m.heading as MetaValue),
        phrasing: flag(m.phrasing as MetaValue),
        embedded: flag(m.embedded as MetaValue),
        interactive: flag(m.interactive as MetaValue),
        labelable: flag(m.labelable as MetaValue),
        form: flag(m.form as MetaValue),
        scriptSupporting: flag(m.scriptSupporting as MetaValue),
      },
      transparent: typeof m.transparent === 'function' ? 'conditional' : Array.isArray(m.transparent) ? m.transparent : m.transparent === true,
      permittedContent: content,
      permittedDescendants: descendants(m.permittedDescendants),
      permittedOrder: list(m.permittedOrder),
      permittedParent: list(m.permittedParent),
      requiredAncestors: list(m.requiredAncestors),
      requiredContent: list(m.requiredContent),
      attributes,
    };
  }
  return {
    $generated: { notice: NOTICE, by: 'tools/gen/generate.ts', from: { 'html-validate': version('html-validate') } },
    elements,
  };
}

// ---------------------------------------------------------------- output

// One entry per line under "properties", "types", "elements" and "icons", so a regenerated file diffs by entry.
function format(data: Record<string, unknown>): string {
  const lines = Object.entries(data).map(([key, value]) => {
    if (Array.isArray(value) && key === 'icons') return `  ${JSON.stringify(key)}: [\n${value.map((v) => `    ${JSON.stringify(v)}`).join(',\n')}\n  ]`;
    if (value !== null && typeof value === 'object' && !Array.isArray(value) && ['properties', 'types', 'elements'].includes(key)) {
      const inner = Object.entries(value as Record<string, unknown>).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)}`);
      return `  ${JSON.stringify(key)}: {\n${inner.join(',\n')}\n  }`;
    }
    return `  ${JSON.stringify(key)}: ${JSON.stringify(value)}`;
  });
  return `{\n${lines.join(',\n')}\n}\n`;
}

export async function generate(root: string = REPO_ROOT): Promise<string[]> {
  const dir = path.join(root, GENERATED_DIR);
  fs.mkdirSync(dir, { recursive: true });
  const written: string[] = [];
  const css = generateCss();
  for (const [file, data] of [[CSS_FILE, css], [COMPAT_FILE, generateCompat(css)], [HTML_FILE, generateHtml()], [ICONS_FILE, generateIconNames()]] as const) {
    fs.writeFileSync(path.join(dir, file), format(data as Record<string, unknown>));
    written.push(`${GENERATED_DIR}/${file}`);
  }
  written.push(...writeTypes(root));
  written.push(writeMotionRuntime(root));
  fs.writeFileSync(path.join(root, ICON_SPRITE), generateSprite(root));
  written.push(ICON_SPRITE);
  return written;
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  for (const file of await generate()) console.log(`gen: wrote ${file}`);
}
