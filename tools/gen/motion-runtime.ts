// The motion runtime as a page's script holds it (spec export-motion-js): each factory of src/editor/motion/runtime/
// and the start, minified one by one (rolldown's minifier, the one Vite builds the editor with), written to
// src/generated/motion-runtime.ts. The page's motion script (runtime/compose.ts motionRuntimeSource) is put together
// from these texts, with only the factories the site uses; the editor's canvas runs the very functions they come from,
// and `npm run gen:check` fails while a source changed and this file was not written again.
import fs from 'node:fs';
import path from 'node:path';
import { minifySync } from 'rolldown/utils';
import { createEasing } from '../../src/core/motion/easing.ts';
import { createNoBehaviours, createNoLottie, createNoSplitText } from '../../src/editor/motion/runtime/absent.ts';
import { createActions } from '../../src/editor/motion/runtime/actions.ts';
import { createBehaviours } from '../../src/editor/motion/runtime/behaviours.ts';
import { createLottie } from '../../src/editor/motion/runtime/lottie.ts';
import { createPlayer } from '../../src/editor/motion/runtime/player.ts';
import { createScroll } from '../../src/editor/motion/runtime/scroll.ts';
import { createSplitText } from '../../src/editor/motion/runtime/split-text.ts';
import { startMotion } from '../../src/editor/motion/runtime/start.ts';
import { createTargets } from '../../src/editor/motion/runtime/targets.ts';
import { createTriggers } from '../../src/editor/motion/runtime/triggers.ts';

export const MOTION_RUNTIME_FILE = 'src/generated/motion-runtime.ts';

const SOURCES = {
  createEasing,
  createTargets,
  createSplitText,
  createActions,
  createLottie,
  createScroll,
  createPlayer,
  createTriggers,
  createBehaviours,
  createNoLottie,
  createNoSplitText,
  createNoBehaviours,
  startMotion,
} as const;

// One function's source, minified as the value of a declaration (so the minifier keeps it whole), then taken back out.
function minified(name: string, source: string): string {
  const held = `var held = ${source};`;
  const result = minifySync(`${name}.js`, held, { mangle: { toplevel: false }, compress: { target: 'es2020' } });
  if (result.errors.length > 0) throw new Error(`motion runtime: ${name} did not minify: ${result.errors.map((error) => error.message).join('; ')}`);
  const code = result.code.trim();
  const match = /^var held\s*=\s*([\s\S]*?);?$/.exec(code);
  if (match === null) throw new Error(`motion runtime: ${name} minified to an unexpected shape: ${code.slice(0, 80)}`);
  return match[1] as string;
}

export function writeMotionRuntime(root: string): string {
  const entries = Object.entries(SOURCES).map(([name, factory]) => `  ${name}: ${JSON.stringify(minified(name, (factory as (...args: never[]) => unknown).toString()))},`);
  const text = [
    '// Generated by `npm run gen` (tools/gen/motion-runtime.ts) from src/editor/motion/runtime/ and core/motion/easing.ts.',
    '// Do not edit: change the runtime and run npm run gen.',
    'export const MINIFIED_RUNTIME = {',
    ...entries,
    '} as const;',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(root, MOTION_RUNTIME_FILE), text);
  return MOTION_RUNTIME_FILE;
}
