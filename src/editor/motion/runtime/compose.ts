// The motion runtime put together (spec motion-runtime): the factories by name, the start the editor calls on its
// canvas's window, and the same functions written as text for a page — one runtime, never two. Each factory is
// written as its own source, so what a page runs is exactly what the editor's tests run.
import { createEasing } from '../../../core/motion/easing.ts';
import { configText, type RuntimeConfig } from '../../../core/motion/export.ts';
import { createActions } from './actions.ts';
import { createBehaviours } from './behaviours.ts';
import { createLottie } from './lottie.ts';
import { createPlayer } from './player.ts';
import { createScroll } from './scroll.ts';
import { createSplitText } from './split-text.ts';
import { startMotion, type Factories, type MotionController, type StartOptions } from './start.ts';
import { createTargets } from './targets.ts';
import { createTriggers } from './triggers.ts';
import { MINIFIED_RUNTIME } from '../../../generated/motion-runtime.ts';

export const FACTORIES: Factories = {
  createEasing,
  createTargets,
  createSplitText,
  createActions,
  createLottie,
  createScroll,
  createPlayer,
  createTriggers,
  createBehaviours,
};

// The runtime started on a window (the canvas's iframe, a test's page).
export const startOn = (win: Window, config: RuntimeConfig, options: StartOptions): MotionController => startMotion(win, config, FACTORIES, options);

// The page's motion script (export: js/motion.js; the preview writes it inline): the factories and the start as their
// own source, minified (src/generated/motion-runtime.ts, written by npm run gen from these very functions), then the
// start run on the page with the site's motion data. Only the parts the site uses are written in full: a site that
// plays no Lottie animation, splits no text or sets no behaviour takes that part's empty stand-in (absent.ts). Plain
// JavaScript, no library, no module (a page opened from file:// runs it too).
export function motionRuntimeSource(config: RuntimeConfig): string {
  const effects = new Set(Object.values(config.timelines).flatMap((timeline) => timeline.actions.map((action) => action.effect.kind)));
  const chosen: Readonly<Record<keyof Factories, keyof typeof MINIFIED_RUNTIME>> = {
    createEasing: 'createEasing',
    createTargets: 'createTargets',
    createSplitText: effects.has('split-text') ? 'createSplitText' : 'createNoSplitText',
    createActions: 'createActions',
    createLottie: effects.has('lottie') ? 'createLottie' : 'createNoLottie',
    createScroll: 'createScroll',
    createPlayer: 'createPlayer',
    createTriggers: 'createTriggers',
    createBehaviours: config.behaviours.length > 0 ? 'createBehaviours' : 'createNoBehaviours',
  };
  const factories = Object.entries(chosen)
    .map(([name, source]) => `${name}:${MINIFIED_RUNTIME[source]}`)
    .join(',');
  return [
    '// Generated by Builder: the motion of the site (interactions, timelines, behaviours). Plain JavaScript on the Web',
    "// Animations API and the browser's scroll timelines; no library.",
    '(function () {',
    "  'use strict';",
    `  var factories = {${factories}};`,
    `  (${MINIFIED_RUNTIME.startMotion})(window, ${configText(config)}, factories, { mode: 'page' });`,
    '})();',
    '',
  ].join('\n');
}
